class ReportDoc(BaseDocTemplate):
    def __init__(self, filename):
        super().__init__(
            str(filename), pagesize=A4,
            leftMargin=22 * mm, rightMargin=22 * mm,
            topMargin=22 * mm, bottomMargin=19 * mm,
            title="Elemental - Τεχνική αναφορά (προσχέδιο)",
            author="Elemental project",
        )
        frame = Frame(
            self.leftMargin, self.bottomMargin, self.width, self.height,
            leftPadding=0, rightPadding=0, topPadding=0, bottomPadding=0,
        )
        self.addPageTemplates(PageTemplate(id="report", frames=frame, onPage=self.draw_page))
        self.heading_count = 0

    def beforeDocument(self):
        self.heading_count = 0

    def draw_page(self, canvas, doc):
        canvas.saveState()
        if doc.page > 1:
            canvas.setStrokeColor(RULE)
            canvas.setLineWidth(0.5)
            canvas.line(22 * mm, A4[1] - 16 * mm, A4[0] - 22 * mm, A4[1] - 16 * mm)
            canvas.setFont("ArialGreek", 8)
            canvas.setFillColor(MUTED)
            canvas.drawString(22 * mm, A4[1] - 13 * mm, "ELEMENTAL | Τεχνική αναφορά")
            canvas.line(22 * mm, 15 * mm, A4[0] - 22 * mm, 15 * mm)
            canvas.drawString(22 * mm, 11 * mm, "Προσχέδιο για έλεγχο")
            canvas.drawRightString(A4[0] - 22 * mm, 11 * mm, str(doc.page))
        canvas.restoreState()

    def afterFlowable(self, flowable):
        if isinstance(flowable, Paragraph) and flowable.style.name == "H1":
            self.heading_count += 1
            label = flowable.getPlainText()
            key = f"heading-{self.heading_count}"
            self.canv.bookmarkPage(key)
            self.notify("TOCEntry", (0, label, self.page, key))


story = []


def p(text, style="body"):
    story.append(Paragraph(text.replace("`", ""), styles[style]))


def h1(text):
    p(text, "h1")


def h2(text):
    p(text, "h2")


def space(height=5 * mm):
    story.append(Spacer(1, height))


def photo(path, width):
    with PILImage.open(path) as image:
        w, h = image.size
    return Image(str(path), width=width, height=width * h / w)


def figure(path, number, caption, width=BODY_W):
    story.append(KeepTogether([
        photo(path, width),
        Paragraph(f"<b>Εικόνα {number}.</b> {caption}", styles["caption"]),
    ]))


def paired(left, right, labels, number, caption):
    col = (BODY_W - 7 * mm) / 2
    grid = Table(
        [[photo(left, col), photo(right, col)],
         [Paragraph(labels[0], styles["small"]), Paragraph(labels[1], styles["small"])]],
        colWidths=[col + 3.5 * mm, col + 3.5 * mm],
    )
    grid.setStyle(TableStyle([
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 0),
        ("RIGHTPADDING", (0, 0), (-1, -1), 7 * mm),
        ("TOPPADDING", (0, 0), (-1, -1), 0),
        ("BOTTOMPADDING", (0, 0), (-1, 0), 2 * mm),
    ]))
    story.append(KeepTogether([
        grid,
        Paragraph(f"<b>Εικόνα {number}.</b> {caption}", styles["caption"]),
    ]))


def info_box(title, text):
    content = Paragraph(f"<b>{title}</b><br/>{text}", styles["small"])
    box = Table([[content]], colWidths=[BODY_W])
    box.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, -1), PALE),
        ("LINEBEFORE", (0, 0), (0, -1), 3, ORANGE),
        ("LEFTPADDING", (0, 0), (-1, -1), 12),
        ("RIGHTPADDING", (0, 0), (-1, -1), 12),
        ("TOPPADDING", (0, 0), (-1, -1), 10),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 8),
    ]))
    story.append(KeepTogether([box, Spacer(1, 8)]))


